-- Paste this whole file into Supabase → SQL Editor → New query, then press Run.
-- Safe to run again: it only creates what is missing and refreshes the rules.

------------------------------------------------------------
-- 1. Staff profiles (role = 'owner' or 'employee')
------------------------------------------------------------
create table if not exists public.profiles (
  id   uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  role text not null default 'employee' check (role in ('owner', 'employee'))
);

create or replace function public.is_owner() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'owner');
$$;

-- Every new login you create in Authentication → Users gets an 'employee' profile.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, name)
  values (new.id, coalesce(nullif(new.raw_user_meta_data->>'name', ''), split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users for each row execute function public.handle_new_user();

-- Users created before this script ran
insert into public.profiles (id, name)
select id, split_part(email, '@', 1) from auth.users
on conflict (id) do nothing;

------------------------------------------------------------
-- 2. Shop settings and menu
------------------------------------------------------------
create table if not exists public.settings (
  id       int primary key default 1 check (id = 1),
  currency text not null default ''
);
insert into public.settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.menu_items (
  id          bigint generated by default as identity primary key,
  name        text not null check (length(name) between 1 and 60),
  price_cents int  not null check (price_cents >= 0),
  sort        int  not null default 0
);

------------------------------------------------------------
-- 3. Orders
------------------------------------------------------------
create table if not exists public.orders (
  id          bigint generated always as identity primary key,
  day         date not null,
  num         int  not null default 0,
  items       jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) > 0),
  total_cents int  not null default 0,
  note        text not null default '' check (length(note) <= 80),
  paid        boolean not null default false,
  paid_at     timestamptz,
  created_at  timestamptz not null default now(),
  created_by  uuid references auth.users(id) on delete set null
);
create index if not exists orders_day_idx on public.orders (day);

-- The database numbers each day's orders (#1, #2 …), adds up the total,
-- and records who logged it and when, so nobody can fake these values.
create or replace function public.orders_before_insert() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if exists (
    select 1 from jsonb_array_elements(new.items) i
    where coalesce((i->>'qty')::int, 0) <= 0
       or coalesce((i->>'cents')::int, -1) < 0
       or coalesce(length(i->>'name'), 0) = 0
  ) then
    raise exception 'Each item needs a name, a quantity above 0 and a price';
  end if;

  perform pg_advisory_xact_lock(hashtext('orders-' || new.day::text));
  select coalesce(max(num), 0) + 1 into new.num from public.orders where day = new.day;
  select coalesce(sum((i->>'qty')::int * (i->>'cents')::int), 0)
    into new.total_cents from jsonb_array_elements(new.items) i;
  new.created_by := auth.uid();
  new.created_at := now();
  new.paid_at    := case when new.paid then now() else null end;
  return new;
end $$;

drop trigger if exists orders_before_insert on public.orders;
create trigger orders_before_insert
  before insert on public.orders for each row execute function public.orders_before_insert();

create or replace function public.orders_before_update() returns trigger
language plpgsql as $$
begin
  if new.paid and not old.paid then new.paid_at := now();
  elsif not new.paid then new.paid_at := null;
  else new.paid_at := old.paid_at;
  end if;
  return new;
end $$;

drop trigger if exists orders_before_update on public.orders;
create trigger orders_before_update
  before update on public.orders for each row execute function public.orders_before_update();

------------------------------------------------------------
-- 4. Who can do what
--    Employees: see the menu, log orders, see and mark paid the last 36 hours of orders.
--    Owner:     all of that, plus every past day, the menu, and deleting orders.
--    Not signed in: nothing.
------------------------------------------------------------
alter table public.profiles   enable row level security;
alter table public.settings   enable row level security;
alter table public.menu_items enable row level security;
alter table public.orders     enable row level security;

revoke all on public.profiles, public.settings, public.menu_items, public.orders from anon;
revoke all on public.profiles, public.settings, public.menu_items, public.orders from authenticated;
grant select on public.profiles to authenticated;
grant select, update on public.settings to authenticated;
grant select, insert, update, delete on public.menu_items to authenticated;
grant select, insert, delete on public.orders to authenticated;
grant update (paid) on public.orders to authenticated;   -- staff can change only "paid"

drop policy if exists "profiles: own or owner" on public.profiles;
create policy "profiles: own or owner" on public.profiles
  for select to authenticated using (id = auth.uid() or public.is_owner());

drop policy if exists "settings: staff read" on public.settings;
create policy "settings: staff read" on public.settings
  for select to authenticated using (true);
drop policy if exists "settings: owner edits" on public.settings;
create policy "settings: owner edits" on public.settings
  for update to authenticated using (public.is_owner()) with check (public.is_owner());

drop policy if exists "menu: staff read" on public.menu_items;
create policy "menu: staff read" on public.menu_items
  for select to authenticated using (true);
drop policy if exists "menu: owner writes" on public.menu_items;
create policy "menu: owner writes" on public.menu_items
  for all to authenticated using (public.is_owner()) with check (public.is_owner());

drop policy if exists "orders: read" on public.orders;
create policy "orders: read" on public.orders
  for select to authenticated
  using (public.is_owner() or created_at > now() - interval '36 hours');
drop policy if exists "orders: log" on public.orders;
create policy "orders: log" on public.orders
  for insert to authenticated with check (true);
drop policy if exists "orders: mark paid" on public.orders;
create policy "orders: mark paid" on public.orders
  for update to authenticated
  using (public.is_owner() or created_at > now() - interval '36 hours') with check (true);
drop policy if exists "orders: owner deletes" on public.orders;
create policy "orders: owner deletes" on public.orders
  for delete to authenticated using (public.is_owner());

------------------------------------------------------------
-- 5. Live updates (new orders appear on every screen without reloading)
------------------------------------------------------------
do $$
begin
  begin alter publication supabase_realtime add table public.orders;     exception when duplicate_object then null; end;
  begin alter publication supabase_realtime add table public.menu_items; exception when duplicate_object then null; end;
  begin alter publication supabase_realtime add table public.settings;   exception when duplicate_object then null; end;
end $$;

